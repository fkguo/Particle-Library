import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart' show rootBundle;
import 'package:sqlite3/sqlite3.dart';

import '../core/app_paths.dart';

/// Prose that pdgLive shows but the PDG database and REST API do not provide:
/// the `was ...` rename line and the short summary paragraph.
@immutable
class PdgNote {
  const PdgNote({this.was, this.summary, this.citations = const {}});

  final String? was;
  final String? summary;

  /// Citation label -> INSPIRE recid, as linked on the pdgLive page.
  final Map<String, int> citations;

  bool get isEmpty => (was ?? '').isEmpty && (summary ?? '').isEmpty;
}

/// Bibliographic record for a citation that appears only in a pdgLive summary
/// and is not part of the official `pdgreference` table.
@immutable
class PdgNoteReference {
  const PdgNoteReference({
    required this.documentId,
    this.inspireRecid,
    this.title,
    this.authors,
    this.year,
    this.publication,
    this.doi,
    this.arxivId,
    this.citeKey,
  });

  final String documentId;
  final int? inspireRecid;
  final String? title;
  final String? authors;
  final int? year;
  final String? publication;
  final String? doi;
  final String? arxivId;

  /// INSPIRE BibTeX key, captured when the patch was generated so the field
  /// works offline.
  final String? citeKey;
}

/// Sidecar SQLite asset with the pdgLive notes, generated by
/// `tool/fetch_pdg_notes.py` for every root identifier of the bundled edition.
///
/// The official snapshot stays untouched (its pinned SHA-256 remains valid);
/// this table only adds the website-only prose.
class PdgNotes {
  PdgNotes._();

  static const String assetPath = 'assets/pdg_notes_2026.sqlite';

  static Map<String, PdgNote>? _cache;
  static Map<String, PdgNoteReference>? _references;
  static Map<String, List<String>>? _citedByEntries;
  static Map<String, List<String>>? _reviewFiles;

  static Future<PdgNote?> forPdgid(String pdgid) async {
    await _ensureLoaded();
    return _cache![pdgid];
  }

  static Future<PdgNoteReference?> referenceFor(String documentId) async {
    await _ensureLoaded();
    return _references![documentId];
  }

  /// Particle identifiers whose pdgLive summary cites [documentId].
  static Future<List<String>> entriesForCitation(String documentId) async {
    await _ensureLoaded();
    return _citedByEntries![documentId] ?? const <String>[];
  }

  /// Review PDFs that pdgLive lists for [pdgid] (empty when unknown).
  static Future<List<String>> reviewFilesFor(String pdgid) async {
    await _ensureLoaded();
    return _reviewFiles![pdgid] ?? const <String>[];
  }

  static Future<String?> citeKeyFor(String documentId) async {
    final reference = await referenceFor(documentId);
    final key = reference?.citeKey;
    return (key == null || key.isEmpty) ? null : key;
  }

  static Future<PdgNoteReference?> referenceForDoi(String doi) async {
    await _ensureLoaded();
    final key = doi.trim().toLowerCase();
    if (key.isEmpty) return null;
    for (final reference in _references!.values) {
      if ((reference.doi ?? '').trim().toLowerCase() == key) return reference;
    }
    return null;
  }

  static Future<void> _ensureLoaded() async {
    if (_cache != null) return;
    final loaded = await _load();
    _cache = loaded.notes;
    _references = loaded.references;
    _citedByEntries = loaded.citedByEntries;
    _reviewFiles = loaded.reviewFiles;
  }

  @visibleForTesting
  static void resetCache() {
    _cache = null;
    _references = null;
    _citedByEntries = null;
    _reviewFiles = null;
  }

  static Future<
    ({
      Map<String, PdgNote> notes,
      Map<String, PdgNoteReference> references,
      Map<String, List<String>> citedByEntries,
      Map<String, List<String>> reviewFiles,
    })
  >
  _load() async {
    try {
      final data = await rootBundle.load(assetPath);
      final bytes = data.buffer.asUint8List(
        data.offsetInBytes,
        data.lengthInBytes,
      );
      final file = await _materialize(bytes);
      final database = sqlite3.open(file.path, mode: OpenMode.readOnly);
      try {
        final citations = <String, Map<String, int>>{};
        try {
          for (final row in database.select(
            'SELECT pdgid, label, inspire_recid FROM pdg_note_citations',
          )) {
            final recid = row['inspire_recid'];
            if (recid is int) {
              (citations[row['pdgid'] as String] ??= {})[row['label']
                      as String] =
                  recid;
            }
          }
        } on SqliteException {
          // Older assets have no citation table.
        }
        final notes = <String, PdgNote>{};
        for (final row in database.select(
          'SELECT pdgid, was, summary FROM pdg_notes',
        )) {
          final pdgid = row['pdgid'] as String;
          notes[pdgid] = PdgNote(
            was: row['was'] as String?,
            summary: row['summary'] as String?,
            citations: citations[pdgid] ?? const {},
          );
        }
        final citedByEntries = <String, List<String>>{};
        for (final row in database.select(
          'SELECT label, pdgid FROM pdg_note_citations',
        )) {
          final label = row['label'] as String;
          (citedByEntries[label] ??= <String>[]).add(row['pdgid'] as String);
        }
        final reviewFiles = <String, List<String>>{};
        try {
          for (final row in database.select(
            'SELECT pdgid, file FROM pdg_note_reviews',
          )) {
            (reviewFiles[row['pdgid'] as String] ??= <String>[]).add(
              row['file'] as String,
            );
          }
        } on SqliteException {
          // Older assets have no related-review table.
        }
        final references = <String, PdgNoteReference>{};
        try {
          for (final row in database.select(
            'SELECT document_id, inspire_recid, title, authors, year, '
            'publication, doi, arxiv_id, cite_key FROM pdg_note_references',
          )) {
            references[row['document_id'] as String] = PdgNoteReference(
              documentId: row['document_id'] as String,
              inspireRecid: row['inspire_recid'] as int?,
              title: row['title'] as String?,
              authors: row['authors'] as String?,
              year: row['year'] as int?,
              publication: row['publication'] as String?,
              doi: row['doi'] as String?,
              arxivId: row['arxiv_id'] as String?,
              citeKey: row['cite_key'] as String?,
            );
          }
        } on SqliteException {
          // Older assets have no reference table.
        }
        return (
          notes: notes,
          references: references,
          citedByEntries: citedByEntries,
          reviewFiles: reviewFiles,
        );
      } finally {
        database.dispose();
      }
    } catch (error) {
      // The notes are an enhancement: a missing asset must not break a page.
      debugPrint('PDG notes unavailable: $error');
      return (
        notes: const <String, PdgNote>{},
        references: const <String, PdgNoteReference>{},
        citedByEntries: const <String, List<String>>{},
        reviewFiles: const <String, List<String>>{},
      );
    }
  }

  /// Copies the bundled database to a readable location (the asset bundle is
  /// not a filesystem path on every platform).
  static Future<File> _materialize(Uint8List bytes) async {
    Directory directory;
    try {
      directory = await appSupportDirectory();
    } catch (_) {
      directory = Directory.systemTemp;
    }
    final file = File('${directory.path}/pdg_notes_2026.sqlite');
    // Always rewrite: the size can stay identical while the content changes
    // (a new review table, updated cite keys), and the file is only a few
    // hundred kilobytes.
    file.writeAsBytesSync(bytes, flush: true);
    return file;
  }
}
