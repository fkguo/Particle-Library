import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart' show rootBundle;
import 'package:sqlite3/sqlite3.dart';

import '../core/app_paths.dart';

/// Prose that pdgLive shows but the PDG database and REST API do not provide:
/// the `was ...` rename line and the short summary paragraph.
@immutable
class PdgNote {
  const PdgNote({this.was, this.summary, this.citations = const {}});

  final String? was;
  final String? summary;

  /// Citation label -> INSPIRE recid, as linked on the pdgLive page.
  final Map<String, int> citations;

  bool get isEmpty => (was ?? '').isEmpty && (summary ?? '').isEmpty;
}

/// Sidecar SQLite asset with the pdgLive notes, generated by
/// `tool/fetch_pdg_notes.py` for every root identifier of the bundled edition.
///
/// The official snapshot stays untouched (its pinned SHA-256 remains valid);
/// this table only adds the website-only prose.
class PdgNotes {
  PdgNotes._();

  static const String assetPath = 'assets/pdg_notes_2026.sqlite';

  static Map<String, PdgNote>? _cache;

  static Future<PdgNote?> forPdgid(String pdgid) async {
    final notes = _cache ??= await _load();
    return notes[pdgid];
  }

  @visibleForTesting
  static void resetCache() => _cache = null;

  static Future<Map<String, PdgNote>> _load() async {
    try {
      final data = await rootBundle.load(assetPath);
      final bytes = data.buffer.asUint8List(
        data.offsetInBytes,
        data.lengthInBytes,
      );
      final file = await _materialize(bytes);
      final database = sqlite3.open(file.path, mode: OpenMode.readOnly);
      try {
        final citations = <String, Map<String, int>>{};
        try {
          for (final row in database.select(
            'SELECT pdgid, label, inspire_recid FROM pdg_note_citations',
          )) {
            final recid = row['inspire_recid'];
            if (recid is int) {
              (citations[row['pdgid'] as String] ??= {})[row['label']
                      as String] =
                  recid;
            }
          }
        } on SqliteException {
          // Older assets have no citation table.
        }
        final notes = <String, PdgNote>{};
        for (final row in database.select(
          'SELECT pdgid, was, summary FROM pdg_notes',
        )) {
          final pdgid = row['pdgid'] as String;
          notes[pdgid] = PdgNote(
            was: row['was'] as String?,
            summary: row['summary'] as String?,
            citations: citations[pdgid] ?? const {},
          );
        }
        return notes;
      } finally {
        database.dispose();
      }
    } catch (error) {
      // The notes are an enhancement: a missing asset must not break a page.
      debugPrint('PDG notes unavailable: $error');
      return const <String, PdgNote>{};
    }
  }

  /// Copies the bundled database to a readable location (the asset bundle is
  /// not a filesystem path on every platform).
  static Future<File> _materialize(Uint8List bytes) async {
    Directory directory;
    try {
      directory = await appSupportDirectory();
    } catch (_) {
      directory = Directory.systemTemp;
    }
    final file = File('${directory.path}/pdg_notes_2026.sqlite');
    if (!file.existsSync() || file.lengthSync() != bytes.length) {
      file.writeAsBytesSync(bytes, flush: true);
    }
    return file;
  }
}
