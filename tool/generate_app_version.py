#!/usr/bin/env python3
"""Generate the runtime app version from pubspec.yaml.

`pubspec.yaml` is the single human-edited source.  The generated Dart constant
is committed so ordinary builds and tests do not need this script; CI runs
`--check` so a version bump without regeneration fails before release.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUBSPEC = ROOT / "pubspec.yaml"
OUT = ROOT / "lib/app/app_version.g.dart"
VERSION = re.compile(
    r"^version:\s*([0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?)(?:\+\S+)?\s*$",
    re.M,
)


def render() -> str:
    match = VERSION.search(PUBSPEC.read_text())
    if not match:
        raise SystemExit("pubspec.yaml has no version line")
    version = match.group(1)
    return (
        "// GENERATED by tool/generate_app_version.py; do not edit by hand.\n"
        "// Source: pubspec.yaml version (build number stripped).\n"
        f"const String generatedAppVersion = '{version}';\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        actual = OUT.read_text() if OUT.exists() else ""
        if actual != expected:
            print(
                "app_version.g.dart is stale; run "
                "python3 tool/generate_app_version.py",
                file=sys.stderr,
            )
            raise SystemExit(1)
        print("app_version.g.dart is current")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(expected)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
